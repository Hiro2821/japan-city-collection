// cities/kobe/camera.js — 神戸のカメラ経路データ（純粋なデータ＋高さ関数。Three.js 非依存）。docs/cities/kobe-spec.md §8。
//   横画面: 進行度 p で書いた時間キー（kt(p)）。縦画面: ROUTE（道の中心線）に沿ったドリー（PathRig）。高さは「地面からの高さ」で書き、H(x,z) を足して絶対値にする（山から海へ下るため）。
//   near は 4 m：樹木・建物・塔へ 4 m 未満に近づかない。終盤は桟橋の先で U ターンし、振り返って北（山）を向く（縦画面は ROUTE の折り返しで先読みを北へ向ける。K-22）。
import { ROUTE, H } from './layout.js';
import { Polyline } from '../../rig.js';

export const GLOBAL0 = 0;
export const DURATION = 7;
const warp = (u) => { const a = u * u * (3 - 2 * u), b = 1 - (1 - u) * (1 - u); return 0.5 * a + 0.5 * b; };
export const kt = (p) => DURATION * warp(Math.min(1, p / 0.94));
const lin = (u) => u;
export const hMax = (x, z) => { let m = -1e9; for (const a of [-8, 0, 8]) for (const b of [-8, 0, 8]) m = Math.max(m, H(x + a, z + b)); return m; };   // 地面メッシュ（16 m 格子）の補間誤差で潜らないよう周囲の最大値
const g = (x, h, z) => [x, hMax(x, z) + h, z];               // 地面からの高さ h → 絶対座標

// 横画面（p, 位置, 注視点, fov）：Z1 掬星台の夕景 / Z2 北野の坂 / Z3 三宮 / Z4 旧居留地・南京町 / Z5 メリケンパーク・ポートタワー / Z6 海上から振り返る
const L = [
  [0.00, g(330, 60, -1900), g(-40, 40, 250), 42],          // Z1：山上から南（海）を見下ろす。西の残照
  [0.08, g(270, 55, -1650), g(-60, 40, 300), 42],
  [0.16, g(190, 40, -1290), g(20, 20, 0), 42],             // 山腹へ下る
  [0.24, g(120, 18, -1040), g(40, 14, -640), 40],          // 北野：坂の上から
  [0.30, g(75, 9, -850), g(40, 12, -600), 38],             // 異人館の前をゆっくり通る
  [0.36, g(45, 9, -690), g(20, 12, -430), 38],
  [0.42, g(30, 11, -500), g(5, 12, -200), 38],             // 山手から市街へ
  [0.48, g(10, 14, -300), g(-10, 14, 20), 38],
  [0.54, g(0, 16, -80), g(-60, 12, 250), 38],              // 三宮
  [0.60, g(-30, 14, 110), g(-120, 10, 320), 38],
  [0.66, g(-110, 8, 280), g(-250, 8, 400), 36],            // 旧居留地
  [0.72, g(-240, 8, 400), g(-380, 9, 440), 36],            // 南京町
  [0.78, g(-310, 10, 530), g(-250, 60, 760), 38],
  [0.84, g(-200, 10, 670), g(-250, 85, 780), 40],          // メリケンパーク：塔を見上げる
  [0.89, g(-160, 14, 800), g(-250, 70, 780), 42],
  [0.92, g(-190, 28, 920), g(-300, 90, 400), 42],          // 海へ張り出し、振り向く
  [0.94, [-330, 55, 1190], [-330, 200, 0], 42],            // 最終構図：海上から北を向く（塔が右、観覧車が左、奥に市街と山）
  [1.00, [-330, 55, 1190], [-330, 200, 0], 42],
];
export const LANDSCAPE_KEYS = L.map(([p, pos, target, fov]) => ({ t: kt(p), pos, target, fov, ease: lin }));

// 縦画面：ROUTE に沿ったドリー。行 = [区間 i, 区間内の割合 u, 地面からの高さ, 注視点の高さ, fov, 相対速度, 先読み距離, 横ずれ]
const poly = new Polyline(ROUTE);
const frac = (i, u) => (poly.cum[i] + u * (poly.cum[i + 1] - poly.cum[i])) / poly.length;
const DOLLY_SRC = [
  [0, 0.00, 70, 20, 56, 0.9, 1400, 0],
  [1, 0.00, 55, 20, 56, 0.9, 1100, 0],
  [2, 0.00, 45, 15, 58, 0.8, 800, 0],
  [3, 0.00, 28, 12, 58, 0.7, 500, 0],
  [4, 0.00, 16, 10, 60, 0.6, 250, 0],
  [5, 0.00, 8, 9, 60, 0.5, 120, 0],
  [6, 0.00, 8, 9, 60, 0.5, 100, 0],
  [7, 0.00, 10, 10, 60, 0.55, 100, 0],
  [8, 0.00, 12, 12, 58, 0.6, 100, 0],
  [9, 0.00, 10, 12, 58, 0.6, 100, 0],
  [10, 0.00, 8, 10, 58, 0.55, 90, 0],
  [11, 0.00, 7, 10, 60, 0.5, 80, 0],
  [12, 0.00, 7, 10, 60, 0.5, 80, 0],
  [13, 0.00, 9, 12, 60, 0.5, 80, 0],
  [14, 0.00, 12, 30, 58, 0.5, 70, 0],
  [15, 0.00, 14, 70, 56, 0.5, 80, 0],
  [16, 0.00, 25, 80, 54, 0.8, 120, 0],
  [17, 0.00, 45, 60, 50, 1.5, 200, 0],
  [18, 0.00, 50, 330, 46, 3.0, 900, 0],                    // 最終：海上（U ターンの折り返し点）から、北（山）へ向き直る
];
export const DOLLY = DOLLY_SRC.map(([i, u, h, th, fov, sp, ahead, side]) => {
  const f = frac(i, u), [x, z] = poly.at(f * poly.length), [tx, tz] = poly.at(f * poly.length + ahead);
  return [f, hMax(x, z) + h, hMax(tx, tz) + th, fov, sp, ahead, side];
});

export const CAM_XZ = []; for (let i = 0; i < LANDSCAPE_KEYS.length - 1; i++) for (let s = 0; s < 8; s++) { const a = LANDSCAPE_KEYS[i].pos, b = LANDSCAPE_KEYS[i + 1].pos, u = s / 8; CAM_XZ.push([a[0] + (b[0] - a[0]) * u, a[2] + (b[2] - a[2]) * u]); }   // 経路の近くに木・家を置かない
export const PATH = { globalStart: GLOBAL0, duration: DURATION, landscapeKeys: LANDSCAPE_KEYS, route: ROUTE, dolly: DOLLY };
